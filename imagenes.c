unsigned char* Imagenes_ObtenerPixeles(unsigned char imagen_id, unsigned char offset_id)
{
    switch (imagen_id)
    {
    case IMAGENES_ID_BLOQUES:
        return imagenes_bloques[offset_id];
        break;
    case IMAGENES_ID_FUENTE:
        return imagenes_fuente[offset_id];
        break;
    }
    return 0;
}

