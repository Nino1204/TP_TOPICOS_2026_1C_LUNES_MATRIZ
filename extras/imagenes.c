unsigned char* Imagenes_ObtenerPixeles(unsigned char imagen_id, unsigned char offset_id)
{
    switch (imagen_id)
    {
    case IMAGENES_ID_BLOQUES:
        return imagenes_bloques[offset_id];
        break;
    case IMAGENES_ID_FUENTE8x8:
        return imagenes_fuente[offset_id];
        break;
    case IMAGENES_ID_FUENTE8x16:
        return imagenes_fuente16[offset_id];
        break;
    case IMAGENES_ID_PALETAS:
        return imagenes_paletas[offset_id];
        break;
    }
    return 0;
}
